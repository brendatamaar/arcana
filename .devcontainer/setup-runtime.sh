#!/usr/bin/env bash
# Choose a sandbox runtime for development and write an Arcana config for it.
#
# Tries to register gVisor (runsc) with the Docker daemon inside the dev container and proves it by
# starting a container. If that fails (common in Codespaces, where nested sandboxes are restricted),
# it falls back to runc with the explicit insecure opt-in and says so loudly. Output files, all under
# $ARCANA_DEV_HOME (default ~/.config/arcana):
#   dev.yaml     the config to pass to `arcana serve --config`
#   RUNTIME      "runsc" or "runc"
#   WARNING      present only for the runc fallback; its text is the banner shown at every start
#
# Environment: ARCANA_DEV_SKIP_INSTALL=1 skips installing gVisor (only detects what is registered),
# ARCANA_DEV_FORCE_RUNC=1 forces the fallback, ARCANA_DEV_DATA_DIR overrides the data directory.
set -uo pipefail

home="${ARCANA_DEV_HOME:-$HOME/.config/arcana}"
data="${ARCANA_DEV_DATA_DIR:-$HOME/.arcana-dev}"
mkdir -p "$home" "$data"
rm -f "$home/WARNING" "$home/RUNTIME"

runsc_registered() { docker info --format '{{json .Runtimes}}' 2> /dev/null | grep -q '"runsc"'; }
runsc_works() { docker run --rm --runtime=runsc --network=none busybox:stable true > /dev/null 2>&1; }

install_runsc() {
  command -v sudo > /dev/null || return 1
  local arch repo
  arch="$(dpkg --print-architecture)"
  repo="https://storage.googleapis.com/gvisor/releases release main"
  sudo apt-get update -qq || return 1
  sudo apt-get install -y -qq apt-transport-https ca-certificates curl gnupg || return 1
  curl -fsSL https://gvisor.dev/archive.key | sudo gpg --dearmor --yes -o /usr/share/keyrings/gvisor-archive-keyring.gpg || return 1
  echo "deb [arch=$arch signed-by=/usr/share/keyrings/gvisor-archive-keyring.gpg] $repo" | sudo tee /etc/apt/sources.list.d/gvisor.list > /dev/null
  sudo apt-get update -qq && sudo apt-get install -y -qq runsc || return 1
  sudo "$(command -v runsc)" install || return 1
  # The runtimes setting is reloadable, so a SIGHUP picks it up without restarting the nested daemon.
  sudo pkill -HUP dockerd || return 1
  for _ in $(seq 1 20); do runsc_registered && return 0; sleep 1; done
  return 1
}

runtime=runc
if [ "${ARCANA_DEV_FORCE_RUNC:-0}" != 1 ]; then
  if ! runsc_registered && [ "${ARCANA_DEV_SKIP_INSTALL:-0}" != 1 ]; then
    echo "setup: installing gVisor (runsc)..." >&2
    install_runsc || echo "setup: gVisor could not be installed here" >&2
  fi
  if runsc_registered && runsc_works; then
    runtime=runsc
  elif runsc_registered; then
    echo "setup: runsc is registered but cannot start a container in this environment" >&2
  fi
fi

insecure=false
if [ "$runtime" = runc ]; then
  insecure=true
  cat > "$home/WARNING" << 'BANNER'
############################################################################
#  INSECURE DEVELOPMENT RUNTIME: gVisor (runsc) is not usable here.         #
#  Sandboxes use runc and SHARE THIS MACHINE'S KERNEL. Do not run untrusted #
#  code. allow_insecure_runtime is on only in ~/.config/arcana/dev.yaml.    #
#  Escape tests cannot prove isolation under runc.                          #
############################################################################
BANNER
fi
echo "$runtime" > "$home/RUNTIME"

cat > "$home/dev.yaml" << YAML
# Generated by .devcontainer/setup-runtime.sh; safe to delete, regenerated on creation.
server:
  listen: 127.0.0.1:7070
  metrics_listen: 127.0.0.1:9090
  destroy_on_shutdown: true
data_dir: $data
runtime:
  docker:
    oci_runtime: $runtime
    allow_insecure_runtime: $insecure
templates:
  - name: base
    image: arcana-base:local
YAML

echo "setup: runtime=$runtime config=$home/dev.yaml" >&2
[ ! -f "$home/WARNING" ] || cat "$home/WARNING" >&2
exit 0
